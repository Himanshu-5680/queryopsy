def table_meta(tables: list[Table]) -> list[dict]:
    out = []
    for t in tables:
        out.append({"name": t.name, "doc": t.doc, "rows": len(t.rows), "columns": [
            {"name": c.name, "type": c.type, "doc": c.doc, "pk": "PRIMARY KEY" in c.extra,
             "fk": c.extra.split("REFERENCES", 1)[1].strip() if "REFERENCES" in c.extra else None} for c in t.columns]})
    return out


def fingerprint_levels(case_slug: str, db_path: pathlib.Path, levels: list[Level]) -> tuple[list[dict], dict]:
    con = sqlite3.connect(db_path)
    out, sols = [], {}
    for n, lv in enumerate(levels, start=1):
        cur = con.execute(lv.solution)
        rows = cur.fetchall()
        if not rows:
            raise SystemExit(f"{case_slug} level {n} '{lv.title}' returns no rows - adjust the case for this data")
        salt = f"queryopsy:{case_slug}:{n}"
        lid = f"{case_slug}-{n}"
        out.append({"id": lid, "n": n, "title": lv.title, "story": lv.story, "task": lv.task, "hints": lv.hints,
                    "concepts": lv.concepts, "starter": lv.starter, "salt": salt,
                    "answer": validator.fingerprint(rows, len(cur.description), salt, lv.ordered)})
        sols[lid] = lv.solution
    con.close()
    return out, sols


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--placeholder", action="store_true", help="ignore data/raw and use generated placeholder samples")
    args = ap.parse_args(argv)
    for d in (RAW, SAMPLES, DB, SCHEMAS):
        d.mkdir(parents=True, exist_ok=True)
    files = [] if args.placeholder else sorted(p for p in RAW.iterdir() if p.suffix.lower() in SUPPORTED)
    taken: set = set()
    cases, solutions, planted, report = [], {}, {}, []
    funding_tables = None
    for cls in ALL:
        ds = cls()
        f = find_file(ds, files, taken)
        if f:
            taken.add(f)
            head, rows = read_table(f)
            placeholder, label = False, f"data/raw/{f.name}"
        else:
            head, rows = ds.placeholder()
            sample = SAMPLES / f"{ds.key}_placeholder.csv"
            with sample.open("w", encoding="utf-8", newline="") as fh:
                w = csv.writer(fh)
                w.writerow(head)
                w.writerows(rows)
            placeholder, label = True, f"data/samples/{sample.name} (PLACEHOLDER - synthetic)"
        recs = ds.records(head, rows)
        tables = ds.build(recs)
        if ds.key == "funding":
            funding_tables = tables
        slug = f"case{ds.case_no:02d}_{ds.key}"
        db_path, sql_path = DB / f"{slug}.sqlite", SCHEMAS / f"{slug}.sql"
        meta = ds.case(tables)
        write_db(db_path, tables)
        write_sql(sql_path, meta["title"], label, tables)
        levels, sols = fingerprint_levels(slug, db_path, ds.levels(tables))
        solutions.update(sols)
        planted[slug] = [p.__dict__ for p in ds.planted]
        cases.append({"id": slug, "no": ds.case_no, **meta, "db": f"data/db/{slug}.sqlite", "sql": f"data/schemas/{slug}.sql",
                      "source": {**ds.source, "file": label, "placeholder": placeholder, "rowsIn": len(recs)},
                      "tables": table_meta(tables), "erd": erd.render(tables, 1), "erdWide": erd.render(tables), "levels": levels})
        report.append(f"{slug:26s} {'PLACEHOLDER' if placeholder else 'REAL':11s} {len(recs):6d} rows in -> "
                      f"{sum(len(t.rows) for t in tables):6d} rows, db {db_path.stat().st_size // 1024} KB, {len(levels)} levels, "
                      f"{len(ds.planted)} planted  <- {label}")
    # case 00 - orientation on the funding database (same file, beginner levels)
    fund = next(c for c in cases if c["id"].endswith("funding"))
    t_levels, t_sols = fingerprint_levels("case00_training", ROOT / fund["db"], training_levels())
    solutions.update(t_sols)
    cases.insert(0, {**{k: fund[k] for k in ("db", "sql", "source", "tables", "erd", "erdWide")}, "id": "case00_training", "no": 0,
                     "title": "Orientation: First Day at the Desk", "industry": "Tutorial",
                     "tagline": "Three warm-up queries. Learn the editor, the schema explorer and how verdicts work.",
                     "client": "Queryopsy Audit Academy",
                     "brief": ["Welcome, Lead Data Auditor. Every case gives you a dossier, a real-world database and a list of findings to prove.",
                               "Write SQL in the editor, press Ctrl+Enter, and the engine tells you instantly how close you are - without revealing the answer.",
                               "Finish these three to unlock your first real case."],
                     "difficulty": "Tutorial", "accent": "lime", "levels": t_levels})
    data = {"app": "Queryopsy", "schema": 1, "generated": dt.date.today().isoformat(), "cases": cases}
    (ROOT / "data" / "cases.json").write_text(json.dumps(data, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    fx = ROOT / "tests" / "fixtures"
    fx.mkdir(parents=True, exist_ok=True)
    (fx / "solutions.json").write_text(json.dumps(solutions, indent=1), encoding="utf-8")
    (ROOT / "data" / "planted.json").write_text(json.dumps(planted, indent=1), encoding="utf-8")
    write_planted_doc(cases, planted)
    write_inputs_doc()
    import runpy
    runpy.run_path(str(ROOT / "tools" / "build_site.py"), run_name="__main__")
    print("\n".join(report))
    total = sum((DB / f"{c['id']}.sqlite").stat().st_size for c in cases if c["no"])
    print(f"total db size: {total / 1024:.0f} KB; levels: {sum(len(c['levels']) for c in cases)}")


def write_planted_doc(cases, planted) -> None:
    lines = ["# Planted anomalies", "",
             "Each case keeps the source rows as they are (only parsing/cleaning) and injects a small, documented set of",
             "anomalies so the forensic puzzles always have a provable answer. Everything below is generated by",
             "`python -m pipeline.build`; re-running it with new raw files regenerates this list.", ""]
    for c in cases:
        if c["no"] == 0:
            continue
        src = c["source"]
        lines += [f"## {c['title']} (`{c['id']}`)", "", f"* Source file: `{src['file']}`", f"* Designed for: {src['name']} - licence {src['licence']}", ""]
        rows = planted.get(c["id"], [])
        lines += ["| Table | Key | What was planted |", "|---|---|---|"] + [f"| {p['table']} | {p['key']} | {p['why']} |" for p in rows] + [""]
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "PLANTED.md").write_text("\n".join(lines), encoding="utf-8")


def write_inputs_doc() -> None:
    """docs/DATA-INPUTS.md: which files the pipeline looks for and which columns it understands."""
    lines = ["# Data inputs", "",
             "Drop your CSV or XLSX exports into `data/raw/` and run `python -m pipeline.build`.",
             "Files are matched by their headers (required columns must be present); the name patterns below break ties.",
             "Header matching ignores case, spaces and punctuation, so `Amount in USD`, `amount_usd` and `AmountUSD` are the same.",
             "If a dataset is missing, a clearly labelled synthetic placeholder is generated instead (`data/samples/`).", ""]
    for cls in ALL:
        ds = cls()
        lines += [f"## Case {ds.case_no:02d} - `{ds.key}`", "",
                  f"* Suggested file name: {', '.join('`data/raw/' + f + '`' for f in ds.expected_files)}",
                  f"* Name patterns: {', '.join('`' + p + '`' for p in ds.patterns)}",
                  f"* Designed for: [{ds.source['name']}]({ds.source['url']}) - licence: {ds.source['licence']}",
                  f"* Max rows kept (deterministic sample): {ds.max_rows:,}", "",
                  "| Column (canonical) | Required | Accepted headers |", "|---|---|---|"]
        for canon, aliases in ds.columns.items():
            lines.append(f"| `{canon}` | {'yes' if canon in ds.required else ''} | {', '.join('`' + a + '`' for a in aliases)} |")
        lines.append("")
    (ROOT / "docs" / "DATA-INPUTS.md").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
