SUPPORTED = (".csv", ".tsv", ".txt", ".xlsx", ".xlsm")


def sql_literal(v) -> str:
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def write_sql(path: pathlib.Path, case_title: str, source: str, tables: list[Table]) -> None:
    with path.open("w", encoding="utf-8", newline="\n") as f:
        f.write(f"-- Queryopsy case database: {case_title}\n-- Source: {source}\n-- Generated by pipeline/build.py - do not edit by hand.\n\n")
        for t in tables:
            f.write(f"-- {t.doc}\n{t.ddl()}\n")
            for i in range(0, len(t.rows), 200):
                chunk = t.rows[i:i + 200]
                f.write(f"INSERT INTO {t.name} VALUES\n" + ",\n".join("(" + ",".join(sql_literal(v) for v in r) + ")" for r in chunk) + ";\n")
            f.write("\n")


def write_db(path: pathlib.Path, tables: list[Table]) -> None:
    path.unlink(missing_ok=True)
    con = sqlite3.connect(path)
    con.execute("PRAGMA page_size = 4096")
    for t in tables:
        con.execute(t.ddl())
        con.executemany(f"INSERT INTO {t.name} VALUES ({','.join('?' * len(t.columns))})", t.rows)
    con.commit()
    con.execute("PRAGMA journal_mode = DELETE")
    con.execute("VACUUM")
    con.close()


def find_file(ds, files: list[pathlib.Path], taken: set) -> pathlib.Path | None:
    best, best_score = None, 0.0
    for f in files:
        if f in taken:
            continue
        try:
            head, _ = read_table(f) if f.stat().st_size < 400_000_000 else (None, None)
        except Exception as e:  # unreadable file: report and skip
            print(f"  ! cannot read {f.name}: {e}")
            continue
        s = ds.score(head or [])
        if s and any(p in f.name.lower() for p in ds.patterns):
            s += 1
        if s > best_score:
            best, best_score = f, s
    return best


