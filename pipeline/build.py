"""Build every case: data/raw/* (or placeholder samples) -> data/db/*.sqlite, data/schemas/*.sql, data/cases.json.

    python -m pipeline.build              # auto-detect files in data/raw/
    python -m pipeline.build --placeholder   # ignore data/raw/, use generated samples

Solutions stay out of the shipped site: they are written to tests/fixtures/solutions.json.
"""
